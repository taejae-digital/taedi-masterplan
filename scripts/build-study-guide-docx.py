def bullet(text, level=0):
    p = doc.add_paragraph(style=None)
    pf = p.paragraph_format
    pf.left_indent = Mm(6 + level * 5)
    pf.first_line_indent = Mm(-3)
    pf.line_spacing = 1.25
    pf.space_after = Pt(2.5)
    r = p.add_run("• " + text)
    run_font(r, size=10)
    return p


