import os
from docx import Document
from docx.shared import Pt, Mm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "archive", "docx", "p2-studypack-12scholars.docx")
os.makedirs(os.path.dirname(OUT), exist_ok=True)

BODY_FONT = "Noto Serif KR"
HEAD_FONT = "Noto Sans KR"
BLACK = RGBColor(0x00, 0x00, 0x00)

doc = Document()

for s in doc.sections:
    s.page_width = Mm(210)
    s.page_height = Mm(297)
    s.top_margin = Mm(28)
    s.bottom_margin = Mm(25)
    s.left_margin = Mm(30)
    s.right_margin = Mm(30)

def add_page_numbers(document):
    for section in document.sections:
        footer = section.footer
        footer.is_linked_to_previous = False
        p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.text = ""
        def field(instr):
            run = p.add_run()
            b = OxmlElement('w:fldChar'); b.set(qn('w:fldCharType'), 'begin')
            i = OxmlElement('w:instrText'); i.set(qn('xml:space'), 'preserve'); i.text = instr
            e = OxmlElement('w:fldChar'); e.set(qn('w:fldCharType'), 'end')
            run._r.append(b); run._r.append(i); run._r.append(e)
            run.font.size = Pt(9); run.font.name = HEAD_FONT; run.font.color.rgb = BLACK
        field("PAGE")
        sep = p.add_run(" / "); sep.font.size = Pt(9); sep.font.name = HEAD_FONT; sep.font.color.rgb = BLACK
        field("NUMPAGES")

def set_run_font(run, name=BODY_FONT, size=10.5, bold=False, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = BLACK
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts'); rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), name)
    rFonts.set(qn('w:ascii'), name)
    rFonts.set(qn('w:hAnsi'), name)

def para(text="", size=10.5, bold=False, italic=False, align=None,
         space_before=0, space_after=5, line=1.5, font=BODY_FONT, indent_first="auto"):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = line
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    if align is not None:
        p.alignment = align
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    if indent_first == "auto":
        if align is None:
            pf.first_line_indent = Mm(4)
    elif indent_first:
        pf.first_line_indent = Mm(indent_first)
    if text:
        r = p.add_run(text)
        set_run_font(r, name=font, size=size, bold=bold, italic=italic)
    return p

def bullet(text, size=10.5, space_after=3):
    p = doc.add_paragraph(style=None)
    pf = p.paragraph_format
    pf.left_indent = Mm(7)
    pf.first_line_indent = Mm(-3.5)
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.45
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    r0 = p.add_run("· ")
    set_run_font(r0, size=size)
    r = p.add_run(text)
    set_run_font(r, size=size)
    return p

def label(text, body, size=10.5, space_after=5):
    """굵은 라벨 + 본문 한 문단."""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.5
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    rl = p.add_run(text + "  ")
    set_run_font(rl, name=HEAD_FONT, size=size, bold=True)
    rb = p.add_run(body)
    set_run_font(rb, size=size)
    return p

def h1(num, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.keep_with_next = True
    r = p.add_run(f"{num}  {text}" if num else text)
    set_run_font(r, name=HEAD_FONT, size=13.5, bold=True)
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement('w:pBdr')
    bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'), 'single'); bottom.set(qn('w:sz'), '8')
    bottom.set(qn('w:space'), '4'); bottom.set(qn('w:color'), '000000')
    pbdr.append(bottom); pPr.append(pbdr)
    return p

def h2(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.keep_with_next = True
    r = p.add_run(text)
    set_run_font(r, name=HEAD_FONT, size=10.5, bold=True)
    return p

def hr(color='808080'):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(4); p.paragraph_format.space_after = Pt(4)
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement('w:pBdr'); bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'),'single'); bottom.set(qn('w:sz'),'4')
    bottom.set(qn('w:space'),'1'); bottom.set(qn('w:color'), color)
    pbdr.append(bottom); pPr.append(pbdr)

def module(no, name_kr, name_en, life, identity, context, concepts, claims, example, link, critiques, questions, script):
    """학자 1명 모듈. context=시대맥락, concepts=[(용어,풀이)], example=구체사례, script=발제스크립트."""
    # 제목줄
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.keep_with_next = True
    r = p.add_run(f"모듈 {no}.  {name_kr}")
    set_run_font(r, name=HEAD_FONT, size=12.5, bold=True)
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement('w:pBdr'); bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'),'single'); bottom.set(qn('w:sz'),'8')
    bottom.set(qn('w:space'),'4'); bottom.set(qn('w:color'),'000000')
    pbdr.append(bottom); pPr.append(pbdr)
    pm = doc.add_paragraph()
    pm.paragraph_format.space_after = Pt(6)
    rm = pm.add_run(f"{name_en} · {life}")
    set_run_font(rm, name=HEAD_FONT, size=9, italic=True)

    h2("① 한 줄 정체")
    para(identity, space_after=6)
    h2("② 어떤 문제에 답하려 했나 — 시대 맥락")
    para(context, space_after=6)
    h2("③ 핵심 개념 풀이")
    for term, gloss in concepts:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.left_indent = Mm(7); pf.first_line_indent = Mm(-3.5)
        pf.space_after = Pt(3); pf.line_spacing = 1.45
        pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        rt = p.add_run(f"· {term} — ")
        set_run_font(rt, name=HEAD_FONT, size=10.5, bold=True)
        rg = p.add_run(gloss)
        set_run_font(rg, size=10.5)
    para(space_after=2)
    h2("④ 핵심 주장")
    for c in claims:
        bullet(c)
    para(space_after=2)
    h2("⑤ 구체 사례로 보기")
    para(example, space_after=6)
    h2("⑥ 우리 P2 논지와의 연결")
    para(link, space_after=6)
    h2("⑦ 균열 · 반론")
    for c in critiques:
        bullet(c)
    para(space_after=2)
    h2("⑧ 팀 토론 질문")
    for i, q in enumerate(questions, 1):
        bullet(f"{q}")
    para(space_after=2)
    h2("⑨ 3분 발제 스크립트 (그대로 읽어도 됨)")
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Mm(5); pf.right_indent = Mm(3)
    pf.space_after = Pt(4); pf.line_spacing = 1.5
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    rq = p.add_run(script)
    set_run_font(rq, size=10, italic=True)
    # 좌측 인용 바
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement('w:pBdr'); left = OxmlElement('w:left')
    left.set(qn('w:val'),'single'); left.set(qn('w:sz'),'18')
    left.set(qn('w:space'),'8'); left.set(qn('w:color'),'000000')
    pbdr.append(left); pPr.append(pbdr)
    para(space_after=4)

